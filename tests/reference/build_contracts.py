def _answer_scales(entry: dict[str, Any]) -> dict[str, int]:
    return {a["field"]: a["scale"] for a in entry["answer"] if a.get("scale")}


def _record_schema(entry: dict[str, Any], description: str) -> dict[str, Any]:
    fields = [
        a for a in entry["answer"] if a["field"].startswith("data.") and "." not in a["field"][5:]
    ]
    scales = _answer_scales(entry)
    properties = {}
    for a in fields:
        note = a["description"][:200]
        if a["field"] in scales:
            note = (
                f"{note} Given as a plain amount (Site.pro Accounting sends it multiplied "
                f"by {scales[a['field']]})."
            ).strip()
        properties[a["field"][5:]] = {"description": note}
    schema: dict[str, Any] = {
        "type": "object",
        "additionalProperties": True,
        "description": description,
    }
    if properties:
        schema["properties"] = properties
    return schema


def _description(row: dict[str, Any], entry: dict[str, Any], kind: str, title: str) -> str:
    if kind == "delete":
        return _delete_description(row, entry, title)
    text = entry["description"].strip()
    if not text or text.rstrip(".").lower() == entry["title"].rstrip(".").lower():
        text = f"{title} in Site.pro Accounting."
    if not text.endswith("."):
        text += "."
    if entry["group"] == "e-commerce":
        text += ' Needs an "API for e-commerce" key in its connection.'
    if kind == "report":
        text += (
            " Returns a task ID: the file comes from Get a generated report file about a "
            "minute later, or use Get a report. Site.pro Accounting offers its reports as "
            "a beta."
        )
    if kind == "create":
        text += " Running the step again can create the record twice."
    if row["danger"] == "irreversible":
        text += " " + plan.accounting_effect(entry)
    return text[:1000]


def _delete_description(row: dict[str, Any], entry: dict[str, Any], title: str) -> str:
    if row["objects"] == "by_ids":
        text = (
            f"{title} in Site.pro Accounting: only the records whose IDs are given, at most "
            f"{MAX_DELETE_IDS} per run."
        )
    else:
        text = f"{title} in Site.pro Accounting: only the one record its inputs name."
    if entry["group"] == "e-commerce":
        text += ' Needs an "API for e-commerce" key in its connection.'
    return text + " Deletion cannot be undone."


def _delete_input(node: dict[str, Any]) -> dict[str, Any]:
    """A deletion's input: positive whole IDs only, a closed short list."""
    item = _input(node)
    schema = item["schema"]
    note = (node.get("description") or "").strip()
    whole = {"type": "integer", "minimum": 1}
    if node["kind"] == "decimal_list":
        item["schema"] = {
            "type": "array",
            "items": whole,
            "minItems": 1,
            "maxItems": MAX_DELETE_IDS,
            "title": node["name"],
            "description": (f"{note} Whole numbers, no repeats, at most {MAX_DELETE_IDS}.".strip()),
        }
    elif node["kind"] in {"object", "object_list"}:
        record = schema["items"] if node["kind"] == "object_list" else schema
        for child in record.get("properties", {}).values():
            child.clear()
            child.update(whole)
        if node["kind"] == "object_list":
            schema.update(minItems=1, maxItems=MAX_DELETE_IDS)
            schema["description"] = (
                f"{note} Each record by its IDs; no repeats, at most {MAX_DELETE_IDS}."
            ).strip()
    elif node["kind"] in {"integer", "decimal"}:
        item["value_type"] = "integer"
        item["schema"] = {**whole, "title": node["name"]}
        if note:
            item["schema"]["description"] = note
    return item


def _upload_inputs(entry: dict[str, Any]) -> list[dict[str, Any]]:
    inputs = []
    for header in entry["headers"]:
        name, kind, title, note = HEADER_INPUTS[header["field"]]
        schema: dict[str, Any] = {
            "type": "integer" if kind == "integer" else "string",
            "title": title,
            "description": header["description"] or note,
        }
        if header["allowed"]:
            schema["enum"] = header["allowed"]
        if kind == "text":
            schema["maxLength"] = 255
        inputs.append(
            {"name": name, "value_type": kind, "required": header["required"], "schema": schema}
        )
    inputs.append(
        {
            "name": "file",
            "value_type": "artifact_handle",
            "required": True,
            "schema": {"title": "File", "description": "A workflow file, up to 8 MB."},
        }
    )
    inputs.append(
        {
            "name": "content_type",
            "value_type": "text",
            "required": False,
            "schema": {
                "type": "string",
                "maxLength": 100,
                "title": "File type",
                "description": "The file's MIME type, for example "
                "application/pdf. Default application/octet-stream.",
            },
        }
    )
    return inputs


