            {
                "name": "count",
                "value_type": "integer",
                "schema": {"type": "integer", "description": "How many records this page holds."},
            },
            {
                "name": "page",
                "value_type": "integer",
                "schema": {"type": ["integer", "null"], "description": "This page's number."},
            },
            {
                "name": "pages",
                "value_type": "integer",
                "schema": {"type": ["integer", "null"], "description": "How many pages there are."},
            },
