def _input(node: dict[str, Any]) -> dict[str, Any]:
    schema = params.schema(node)
    schema["title"] = node["name"]
    item: dict[str, Any] = {
        "name": node["name"],
        "value_type": params.value_type(node),
        "required": bool(node.get("required")),
        "schema": schema,
    }
    return item


def _list_info(entry: dict[str, Any]) -> dict[str, Any]:
    names = {p["field"]: p for p in entry["params"]}
    rows_text = names.get("rows", {}).get("description", "")
    rows = sorted({int(n) for n in _ROWS_RE.findall(rows_text) if 0 < int(n) <= 1000}) or [
        10,
        20,
        30,
        50,
        100,
        200,
        500,
    ]
    fields = [
        a["field"][5:]
        for a in entry["answer"]
        if a["field"].startswith("data.") and "." not in a["field"][5:]
    ]
    return {
        "rows": rows,
        "default_rows": 100 if 100 in rows else rows[-1],
        "page": "page" in names,
        "cursor": "cursor" in names,
        "fields": sorted(set(fields)),
    }


